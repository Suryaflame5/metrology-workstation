import json
import xml.etree.ElementTree as ET

class QIFParser:
    def __init__(self, filepath):
        self.filepath = filepath
        self.plan = None

    def parse(self):
        if self.filepath.endswith('.json'):
            with open(self.filepath, 'r') as f:
                self.plan = json.load(f)
        elif self.filepath.endswith('.xml'):
            tree = ET.parse(self.filepath)
            self.plan = self._xml_to_dict(tree.getroot())
            
    def _xml_to_dict(self, root):
        return {"root": root.tag}

    def validate_schema(self):
        return True

    def extract_characteristics(self):
        if not self.plan:
            return []
        return self.plan.get('characteristics', [])

    def to_calibra_format(self):
        chars = self.extract_characteristics()
        return {"calibra_procedure": chars}

